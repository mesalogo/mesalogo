/**
 * scan-hardcoded-cjk.js
 *
 * Scans frontend/src for hard-coded CJK (Chinese) text that bypasses i18n.
 *
 * Goals:
 *   - Highlight strings that the END USER will SEE (JSX text, common antd
 *     props like title/label/placeholder/okText, message.success/error/...).
 *   - Filter out things that are clearly NOT user-visible: code comments
 *     (// or /* ...), `console.*` calls, and the locales/ folder itself.
 *
 * Run:
 *   node scripts/scan-hardcoded-cjk.js
 *   node scripts/scan-hardcoded-cjk.js --md > docs/agents/i18n-hardcoded-cjk-report.md
 *
 * The `--md` flag produces a Markdown report sorted by hot-spot count, which
 * we commit into docs/agents/ so future contributors can see the trend.
 */

const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const SRC = path.join(ROOT, 'src');

const CJK = /[\u4e00-\u9fff]/;
const UI_PROP = /(title|label|placeholder|okText|cancelText|tab|tooltip|description|tip|header|footerText)\s*[:=]\s*["'][^"']*[\u4e00-\u9fff]/;
const MESSAGE_CALL = /\b(message|notification|Modal)\.(success|error|warning|info|warn|confirm)\(\s*["'][^"']*[\u4e00-\u9fff]/;
const JSX_TEXT = />\s*[^<>{}]*[\u4e00-\u9fff][^<>{}]*</;
const FALLBACK_OR = /\bt\([^)]+\)\s*\|\|\s*['"][^'"]*[\u4e00-\u9fff]/;

const md = process.argv.includes('--md');

function* walk(dir) {
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, e.name);
    if (e.isDirectory()) {
      if (/(^|\/)(locales|__tests__|node_modules|build|dist)(\/|$)/.test(p)) continue;
      yield* walk(p);
    } else if (/\.(tsx|jsx|ts|js)$/.test(e.name)) {
      yield p;
    }
  }
}

const perFile = []; // [{file, total, userVisible, categories: {jsx,prop,message,fallback}, samples: []}]
let grandTotalLines = 0;
let grandUserVisible = 0;

for (const file of walk(SRC)) {
  const rel = path.relative(SRC, file);
  if (rel.startsWith('locales/')) continue;
  const src = fs.readFileSync(file, 'utf8');
  const lines = src.split('\n');
  let total = 0;
  let userVisible = 0;
  const cat = { jsx: 0, prop: 0, message: 0, fallback: 0, other: 0 };
  const samples = [];
  for (let i = 0; i < lines.length; i++) {
    const line = lines[i];
    if (!CJK.test(line)) continue;
    total++;
    // Skip pure-comment lines.
    const trimmed = line.trimStart();
    if (trimmed.startsWith('//')) continue;
    if (trimmed.startsWith('*')) continue;
    if (trimmed.startsWith('/*')) continue;
    // Skip console.* calls.
    if (/\bconsole\.\w+\s*\(/.test(line) && !/[<>{]/.test(line)) continue;
    // It's likely user-visible. Categorise.
    let hit = false;
    if (UI_PROP.test(line))      { cat.prop++;     hit = true; }
    if (MESSAGE_CALL.test(line)) { cat.message++;  hit = true; }
    if (JSX_TEXT.test(line))     { cat.jsx++;      hit = true; }
    if (FALLBACK_OR.test(line))  { cat.fallback++; hit = true; }
    if (!hit) cat.other++;
    userVisible++;
    if (samples.length < 3) {
      samples.push({ line: i + 1, text: line.trim().slice(0, 160) });
    }
  }
  grandTotalLines += total;
  grandUserVisible += userVisible;
  if (userVisible > 0) {
    perFile.push({ file: rel, total, userVisible, cat, samples });
  }
}

perFile.sort((a, b) => b.userVisible - a.userVisible);

if (md) {
  console.log('# Hard-coded CJK report (auto-generated)\n');
  console.log('> Generated by `frontend/scripts/scan-hardcoded-cjk.js`. Re-run after each batch of i18n cleanup to track progress.\n');
  console.log(`- Files with user-visible CJK: **${perFile.length}**`);
  console.log(`- Total CJK lines (incl. comments): **${grandTotalLines}**`);
  console.log(`- User-visible CJK lines (excl. comments/console.*): **${grandUserVisible}**\n`);
  console.log('## Top 60 hot files\n');
  console.log('| Rank | File | UV | JSX | Prop | Toast | Fallback || Other |');
  console.log('|---|---|---:|---:|---:|---:|---:|---:|');
  perFile.slice(0, 60).forEach((f, i) => {
    console.log(`| ${i + 1} | \`${f.file}\` | ${f.userVisible} | ${f.cat.jsx} | ${f.cat.prop} | ${f.cat.message} | ${f.cat.fallback} || ${f.cat.other} |`);
  });
  console.log('\n## Sample lines (top 20 files)\n');
  perFile.slice(0, 20).forEach(f => {
    console.log(`### \`${f.file}\` (${f.userVisible} UV lines)\n`);
    f.samples.forEach(s => console.log(`- L${s.line}: \`${s.text.replace(/`/g, '\\`')}\``));
    console.log('');
  });
} else {
  console.log(`Files with user-visible CJK: ${perFile.length}`);
  console.log(`Total CJK lines             : ${grandTotalLines}`);
  console.log(`User-visible CJK lines      : ${grandUserVisible}\n`);
  console.log('Top 30 hot files:');
  console.log('  UV   JSX  Prop  Msg  Fallback  Other  File');
  for (const f of perFile.slice(0, 30)) {
    console.log(
      `  ${String(f.userVisible).padStart(4)} ` +
      `${String(f.cat.jsx).padStart(5)} ` +
      `${String(f.cat.prop).padStart(5)} ` +
      `${String(f.cat.message).padStart(4)} ` +
      `${String(f.cat.fallback).padStart(9)} ` +
      `${String(f.cat.other).padStart(6)}  ${f.file}`
    );
  }
}
